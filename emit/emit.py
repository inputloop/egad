def kde_colors(theme, resolved):
    r = resolved[theme]
    rgb = lambda k: ",".join(map(str, hex_to_rgb(r[k])))
    def group(name, bg, bgalt, fg, extra=""):
        return (f"[Colors:{name}]\nBackgroundNormal={rgb(bg)}\nBackgroundAlternate={rgb(bgalt)}\n"
                f"ForegroundNormal={rgb(fg)}\nForegroundInactive={rgb('text-dim')}\nForegroundActive={rgb('link')}\n"
                f"ForegroundLink={rgb('link')}\nForegroundVisited={rgb('priority')}\nForegroundNegative={rgb('signal-error')}\n"
                f"ForegroundNeutral={rgb('signal-warning')}\nForegroundPositive={rgb('signal-success')}\n"
                f"DecorationFocus={rgb('focus-ring')}\nDecorationHover={rgb('canvas-line')}\n{extra}")
    return "\n".join([
        f"# egad -> KDE Plasma colour scheme. GENERATED by emit/emit.py. Stretch target: untested on a live Plasma.",
        f"[General]\nName=egad {theme}\nColorScheme=egad-{theme}\nshadeSortColumn=true\n",
        group("View", "canvas", "canvas-dim", "text"),
        group("Window", "canvas-dim", "canvas", "text"),
        group("Button", "canvas-inactive", "canvas-dim", "text"),
        group("Selection", "canvas-region", "canvas-line", "text"),
        group("Tooltip", "canvas-dim", "canvas", "text"),
        group("Header", "canvas-active", "canvas-inactive", "text"),
        f"[WM]\nactiveBackground={rgb('canvas-active')}\nactiveForeground={rgb('text')}\n"
        f"inactiveBackground={rgb('canvas-inactive')}\ninactiveForeground={rgb('text-dim')}\n",
    ])


# ---------------------------------------------------------------- main

def main(tokens_path, dist):
    gate = subprocess.run([sys.executable, str(ROOT / "tokens/tokens_check.py"), str(tokens_path)],
                          capture_output=True, text=True)
    if gate.returncode != 0:
        sys.stderr.write(gate.stdout + gate.stderr)
        raise SystemExit("emit: the gate failed; nothing written")
    t, themes, raw, usage, resolved, alias_of = load(tokens_path)
    dist = pathlib.Path(dist)
    w = lambda rel, text: (dist / rel).parent.mkdir(parents=True, exist_ok=True) or (dist / rel).write_text(text) or print("wrote", dist / rel)

    css = css_tokens(t, themes, raw, resolved, alias_of)
    w("css/egad-tokens.css", css)
    structure = (ROOT / "org-html/egad.structure.css").read_text()
    w("org-html/egad.css", css + "\n" + structure)
    for th in themes:
        w(f"elpa-src/egad-{th}-theme.el", deftheme(th, resolved, f"modus-{th}"))
        w(f"adapters/egad-{th}.colors", kde_colors(th, resolved))
    w("adapters/nextcloud.css", nextcloud_css(themes, resolved))
    w("adapters/element-custom-themes.json", element_json(themes, resolved))
    w("tokens-resolved.json", json.dumps({"version": VERSION, "themes": themes, "color": resolved,
                                          "usage": usage, "type": t["type"], "spacing": t.get("spacing"),
                                          "radius": t.get("radius")}, indent=1) + "\n")


if __name__ == "__main__":
    a = sys.argv[1:]
    main(pathlib.Path(a[0]) if a else ROOT / "tokens/egad-tokens.json", a[1] if len(a) > 1 else ROOT / "dist")
