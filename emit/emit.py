def deftheme(theme, resolved, modus_name):
    r = resolved[theme]
    name = f"egad-{theme}"
    specs = []
    for face, fg, bg, extra in FACES:
        parts = []
        if fg:
            parts.append(f':foreground "{r[fg]}"')
        if bg:
            parts.append(f':background "{r[bg]}"')
        if extra:
            parts.append(extra % r if "%(" in extra else extra)
        specs.append(f"   `({face} ((t ({' '.join(parts)}))))")
    light = "light" if theme == "operandi" else "dark"
    return f""";;; {name}-theme.el --- egad {theme}: the egad design tokens as an Emacs theme  -*- lexical-binding: t; -*-

;; Version: {VERSION}
;; Package-Requires: ((emacs "27.1"))
;; Keywords: faces
;; URL: https://egad.bru.st/

;; GENERATED by emit/emit.py from tokens/egad-tokens.json on {datetime.date.today().isoformat()}.
;; Do not edit: change the tokens and run emit again.

;;; Commentary:

;; The egad tokens trace to GNU Emacs's Modus themes ({modus_name}); this theme
;; is what the same tokens look like back in Emacs.  Every face colour here is
;; also a CSS custom property in egad-tokens.css and a value in each platform
;; adapter, so a web page, a Nextcloud instance and this buffer agree.

;;; Code:

(deftheme {name}
  "egad design tokens, {theme} ({light}).")

(custom-theme-set-faces
 '{name}
{chr(10).join(specs)})

;;;###autoload
(when (and (boundp 'custom-theme-load-path) load-file-name)
  (add-to-list 'custom-theme-load-path
               (file-name-as-directory (file-name-directory load-file-name))))

(provide-theme '{name})

;;; {name}-theme.el ends here
"""


