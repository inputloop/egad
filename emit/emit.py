#!/usr/bin/env python3
"""emit.py -- one source, several derivations.

Reads tokens/egad-tokens.json and writes, under dist/:

  css/egad-tokens.css              CSS custom properties, both themes
  org-html/egad.css                the org-mode HTML export theme (tokens + org-html/egad.structure.css)
  elpa-src/egad-<theme>-theme.el   an Emacs deftheme per theme, as a single-file package
  adapters/nextcloud.css           Nextcloud's documented theming variables, set from the tokens
  adapters/element-custom-themes.json   Element Web config.json fragment (setting_defaults.custom_themes)
  adapters/egad-<theme>.colors     KDE Plasma colour scheme (INI)
  tokens-resolved.json             every token, every theme, aliases resolved (for other tools)

Nothing here is hand-edited afterwards: change the tokens, run emit again.
Run tokens/tokens_check.py first; emit refuses tokens the gate would refuse.

    python3 emit/emit.py [tokens/egad-tokens.json] [dist]
"""
import json, re, sys, pathlib, subprocess, datetime

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
VERSION = "0.1.0"


def load(path):
    t = json.load(open(path))
    themes = [th["id"] for th in t["color"]["themes"]]
    raw = {tok["name"]: tok["value"] for tok in t["color"]["tokens"]}
    usage = {tok["name"]: tok.get("usage", "") for tok in t["color"]["tokens"]}

    def val(name, theme, depth=0):
        v = raw[name]
        v = v.get(theme, v.get(themes[0])) if isinstance(v, dict) else v
        m = re.fullmatch(r"\{([^}]+)\}", v)
        if m:
            if depth > 16 or m.group(1) == name or m.group(1) not in raw:
                raise SystemExit(f"alias {name} -> {m.group(1)} does not resolve")
            return val(m.group(1), theme, depth + 1)
        return v.lower()

    def alias_of(name):
        v = raw[name]
        if isinstance(v, str):
            m = re.fullmatch(r"\{([^}]+)\}", v)
            return m.group(1) if m else None
        return None

    resolved = {th: {n: val(n, th) for n in raw} for th in themes}
    return t, themes, raw, usage, resolved, alias_of


def hex_to_rgb(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


# ---------------------------------------------------------------- CSS

def css_tokens(t, themes, raw, resolved, alias_of):
    first = themes[0]
    out = ["/* egad tokens -- GENERATED by emit/emit.py from tokens/egad-tokens.json; do not edit */"]

    def block(theme):
        lines = []
        for n in raw:
            a = alias_of(n)
            lines.append(f"  --egad-{n}: {'var(--egad-' + a + ')' if a else resolved[theme][n]};")
        return "\n".join(lines)

    out.append(f':root, [data-theme="{first}"] {{\n{block(first)}\n}}')
    for th in themes[1:]:
        out.append(f'[data-theme="{th}"] {{\n{block(th)}\n}}')
        out.append(f'@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme="{first}"]) {{\n' +
                   "\n".join("  " + l for l in block(th).splitlines()) + "\n  }\n}")
    misc = []
    for key, stack in t["type"]["families"].items():
        misc.append(f"  --egad-font-{key}: {stack};")
    for fam in ("spacing", "radius"):
        for tok in t.get(fam, {}).get("tokens", []):
            misc.append(f"  --egad-{tok['name']}: {tok['value']};")
    out.append(":root {\n" + "\n".join(misc) + "\n}")
    for g in t["type"]["groups"]:
        fam = g["family"]
        for s in g["styles"]:
            out.append(f".egad-{s['name']} {{ font-family: var(--egad-font-{fam}); font-size: {s['fontSize']}; "
                       f"line-height: {s['lineHeight']}; font-weight: {s['fontWeight']}; }}")
    return "\n\n".join(out) + "\n"


